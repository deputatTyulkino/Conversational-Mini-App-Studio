NONE_BONUS = 0.75


def rules_scorer(text: str) -> dict[str, float]:
    """Оценивает текст по ключевым словам.

    Шаги:
        1. Вырезает текст в «кавычках»: по правилу R9 названия книг, статей
           и файлов на метку не влияют.
        2. Делит текст на слова через re.findall(r"\\w+"), без пунктуации.
        3. Каждая найденная основа или фраза даёт своему классу 1 очко
           (повтор того же слова очков не добавляет). Класс NONE_CLASS
           сразу получает фору NONE_BONUS: если ключевых слов почти нет,
           побеждает «ответить текстом».
        4. Делит очки каждого класса на сумму очков.

    Args:
        text: уже нормализованный текст (это делает ToolRouterService).

    Returns:
        Оценки четырёх классов, каждая от 0 до 1, в сумме 1.
    """
    text = re.sub(r"«[^»]*»", " ", text)
    words = re.findall(r"\w+", text)
    joined = " " + " ".join(words) + " "

    points = {name: 0.0 for name in STEMS}
    points[NONE_CLASS] += NONE_BONUS

    for name, stems in STEMS.items():
        for stem in stems:
            if any(word.startswith(stem) for word in words):
                points[name] += 1

    for name, phrases in PHRASES.items():
        for phrase in phrases:
            if " " + phrase in joined:
                points[name] += 1

    total = sum(points.values())
    return {name: value / total for name, value in points.items()}
